function labeled(
  locale: Locale,
  table: Record<string, Record<Locale, string>>,
  value: string,
): string {
  return table[value]?.[locale] ?? value;
}

export function departmentLabel(locale: Locale, value: string): string {
  return labeled(locale, DEPARTMENTS, value);
}

export function statusLabel(locale: Locale, value: string): string {
  return labeled(locale, STATUSES, value);
}

export function countryLabel(locale: Locale, value: string): string {
  return labeled(locale, COUNTRIES, value);
}

export function roleLabel(locale: Locale, value: string): string {
  return labeled(locale, ROLES, value);
}

export function groupLabel(locale: Locale, value: string): string {
  if (value === 'All') return text(locale, 'common.all');
  if (value === 'Suppressed') return text(locale, 'analytics.suppressed');
  return (
    DEPARTMENTS[value]?.[locale] ??
    STATUSES[value]?.[locale] ??
    COUNTRIES[value]?.[locale] ??
    value
  );
}
